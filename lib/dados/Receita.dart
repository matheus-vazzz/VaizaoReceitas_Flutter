class Receita{
  const Receita(this.nome, this.tipo, this.categoria, this.tempo, this.dificuldade, this.nota, this.porcoes, this.ingredientes, this.preparo, this.favorito);

  final String nome;
  final String tipo;
  final String categoria;
  final String tempo;
  final String dificuldade;
  final String nota;
  final String porcoes;
  final String ingredientes;
  final String preparo;
  final bool favorito;
}